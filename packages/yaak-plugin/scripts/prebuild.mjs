// Precompiles Kiseki and bundles the Vite-free engine into `generated/engine.cjs`, so the plugin can
// build sites inside Yaak without Node.js or npm on the user's machine.
//
// 1. Kiseki's client assets (island runtime, CSS, fonts) and SSR entry are built once with Vite,
//    with a relative base so they work under any `base`.
// 2. `src/engine.ts` (yaakdoc/static + the precompiled theme) is bundled into one CommonJS file.
//    `yaak plugin build` can't bundle it itself: its single-file output doesn't allow the dynamic
//    imports Shiki uses for languages and themes.
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";
import { bundleTheme, resolveContext } from "yaakdoc";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const generated = join(root, "generated");

await rm(generated, { recursive: true, force: true });
await mkdir(generated, { recursive: true });

// 1. Precompile Kiseki. The export only has to be valid: the theme bundle doesn't depend on it.
const work = await mkdtemp(join(tmpdir(), "yaakdoc-plugin-"));
const clientDir = join(work, "client");

try {
  const context = await resolveContext({
    cwd: work,
    exportData: { yaakSchema: 4, resources: { workspaces: [{ id: "wk_prebuild", name: "x" }] } },
    overrides: { theme: "kiseki" },
  });

  const { assets, ssrEntry } = await bundleTheme(context, clientDir, { base: "./" });

  await writeFile(join(generated, "kiseki-server.mjs"), await readFile(ssrEntry));
  await rm(dirname(ssrEntry), { recursive: true, force: true });

  const files = {};

  for (const entry of await readdir(clientDir, { recursive: true, withFileTypes: true })) {
    if (entry.isFile()) {
      const path = join(entry.parentPath, entry.name);

      files[relative(clientDir, path).split(sep).join("/")] = (await readFile(path)).toString(
        "base64",
      );
    }
  }

  await writeFile(
    join(generated, "kiseki-client.ts"),
    [
      "// Generated by scripts/prebuild.mjs. Do not edit.",
      'import type { Assets } from "@yaakdoc/react";',
      "",
      "/** Client assets, relative to the output directory. */",
      `export const assets: Assets = ${JSON.stringify(assets)};`,
      "",
      "/** Client files (base64), keyed by their path in the output directory. */",
      `export const files: Record<string, string> = ${JSON.stringify(files)};`,
      "",
    ].join("\n"),
  );

  await writeFile(
    join(generated, "kiseki-server.d.mts"),
    'export declare const render: import("yaakdoc/static").RenderEntry["render"];\n',
  );
} finally {
  await rm(work, { recursive: true, force: true });
}

// 2. Bundle the engine.
const bundle = await rolldown({
  input: join(root, "src/engine.ts"),
  platform: "node",
  plugins: [
    {
      // Only Kiseki's `vitePlugins` imports it, which the engine never calls. It ships native
      // binaries, so it's replaced with a stub.
      name: "stub-tailwind-vite",
      resolveId: (id) => (id === "@tailwindcss/vite" ? "\0stub-tailwind-vite" : null),
      load: (id) =>
        id === "\0stub-tailwind-vite"
          ? 'export default () => { throw new Error("Vite plugins are not available here."); };'
          : null,
    },
  ],
  transform: { define: { "process.env.NODE_ENV": JSON.stringify("production") } },
  logLevel: "warn",
});

await bundle.write({ file: join(generated, "engine.cjs"), format: "cjs", codeSplitting: false });
await bundle.close();
